/**
 * inject-photos.js
 * ─────────────────────────────────────────────────────────────────
 * Reads ./public/photos.json and replaces the two SVG placeholder
 * blocks in index.html with real <img> tags pointing to the
 * downloaded salon photos.
 *
 * Usage:  node scripts/inject-photos.js
 * ─────────────────────────────────────────────────────────────────
 */

const fs   = require('fs');
const path = require('path');

const INDEX_PATH  = path.join(__dirname, '..', 'index.html');
const PHOTOS_PATH = path.join(__dirname, '..', 'public', 'photos.json');

if (!fs.existsSync(PHOTOS_PATH)) {
  console.error('❌ public/photos.json not found. Run `npm run scrape` first.');
  process.exit(1);
}

const photos = JSON.parse(fs.readFileSync(PHOTOS_PATH, 'utf8'));

if (photos.length === 0) {
  console.error('❌ photos.json is empty. No photos to inject.');
  process.exit(1);
}

let html = fs.readFileSync(INDEX_PATH, 'utf8');

// ── Hero image (first photo) ──────────────────────────────────────
const heroPhoto = photos[0];
const heroImgTag = `<img
          src="/public/${heroPhoto.filename}"
          alt="New Super Natural Nail & Spa — salon interior"
          style="width:100%;height:100%;object-fit:cover;filter:saturate(0.85);"
          loading="eager"
        />`;

// Replace the SVG nail-art placeholder in the hero
html = html.replace(
  /<svg class="nail-art-svg"[\s\S]*?<\/svg>/,
  heroImgTag
);

// ── About image (second photo, or first if only one) ──────────────
const aboutPhoto = photos.length > 1 ? photos[1] : photos[0];
const aboutImgTag = `<img
            src="/public/${aboutPhoto.filename}"
            alt="New Super Natural Nail & Spa — nail technician at work"
            style="width:100%;height:100%;object-fit:cover;"
            loading="lazy"
          />`;

// Replace the SVG botanical placeholder in the about section
html = html.replace(
  /<svg viewBox="0 0 560 500"[\s\S]*?<\/svg>/,
  aboutImgTag
);

// ── Additional photos: inject a gallery section if 3+ photos ──────
if (photos.length >= 3) {
  const galleryPhotos = photos.slice(2, 8); // up to 6 gallery shots
  const galleryItems = galleryPhotos.map(p => `
        <div style="overflow:hidden;background:var(--sage-lt);">
          <img
            src="/public/${p.filename}"
            alt="Salon photo"
            style="width:100%;height:220px;object-fit:cover;display:block;transition:transform 0.4s;"
            loading="lazy"
            onmouseover="this.style.transform='scale(1.04)'"
            onmouseout="this.style.transform='scale(1)'"
          />
        </div>`).join('\n');

  const gallerySection = `
  <!-- PHOTO GALLERY (auto-generated by inject-photos.js) -->
  <section style="padding: var(--space-xl) 0; background: var(--cream);">
    <div class="container">
      <div class="section-header">
        <p class="label">Our Salon</p>
        <div class="divider"></div>
        <h2>Gallery</h2>
      </div>
      <div style="display:grid;grid-template-columns:repeat(auto-fill,minmax(260px,1fr));gap:var(--space-sm);margin-top:var(--space-md);">
        ${galleryItems}
      </div>
    </div>
  </section>`;

  // Inject before the booking banner
  html = html.replace(
    /<!-- BOOKING BANNER -->/,
    `${gallerySection}\n\n  <!-- BOOKING BANNER -->`
  );
}

fs.writeFileSync(INDEX_PATH, html);
console.log(`✅ index.html updated with ${Math.min(photos.length, 2)} hero/about photos.`);
if (photos.length >= 3) {
  console.log(`✅ Gallery section added with ${Math.min(photos.length - 2, 6)} additional photos.`);
}
console.log('\nNext: git add -A && git commit -m "Add real salon photos" && git push');
